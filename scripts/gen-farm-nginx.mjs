/**
 * Generates the nginx datacenter/farm ASN deny map on the VPS.
 *
 *   /etc/nginx/conf.d/zz-farm-asn.conf   → geo $farm_asn { CIDR 1; ... }
 *   /etc/nginx/snippets/farm_asn_filter.conf → `if ($farm_asn) { return 403; }`
 *   sites-enabled/*                        → idempotent `include` after the
 *                                            junk_filter include (443 blocks)
 *
 * Run: node scripts/gen-farm-nginx.mjs [--refresh] [--dry-run]
 * Scheduled weekly via PM2 (pmp-farm-asn-map) — prefix lists drift slowly.
 */

import fs from 'node:fs';
import { execSync } from 'node:child_process';
import { getFarmCidrs, FARM_ASNS } from './lib/farm-asn.mjs';

const DRY = process.argv.includes('--dry-run');
const REFRESH = process.argv.includes('--refresh');

const GEO_FILE = '/etc/nginx/conf.d/zz-farm-asn.conf';
const SNIPPET = '/etc/nginx/snippets/farm_asn_filter.conf';
const SITES_DIR = '/etc/nginx/sites-enabled';
const INCLUDE_LINE = '    include /etc/nginx/snippets/farm_asn_filter.conf;';
const JUNK_INCLUDE = 'include /etc/nginx/snippets/junk_filter.conf;';

const cidrs = await getFarmCidrs({ refresh: REFRESH });
console.log(`${cidrs.length} v4 prefixes across ${FARM_ASNS.length} farm ASNs`);
if (!cidrs.length) { console.error('no prefixes — refusing to write an empty deny map'); process.exit(1); }

// Dedupe: sort by start and drop prefixes whose end is already covered —
// O(n): with start-asc order a prefix is contained iff its end <= running
// max end of all earlier ranges. RIPEstat returns overlapping announcements
// (e.g. /24 inside /22) which make nginx emit "duplicate network" warnings.
const ip2i = (ip) => ip.split('.').reduce((n, o) => n * 256 + Number(o), 0);
let maxEnd = -1;
const deduped = cidrs
  .map((c) => {
    const [ip, bits] = c.cidr.split('/');
    const start = ip2i(ip);
    return { ...c, start, end: start + 2 ** (32 - Number(bits)) - 1 };
  })
  .sort((a, b) => a.start - b.start || b.end - a.end)
  .filter((c) => {
    if (c.end <= maxEnd) return false;
    maxEnd = c.end;
    return true;
  });
console.log(`${deduped.length} unique prefixes after dedupe (-${cidrs.length - deduped.length} contained)`);

const geo = [
  '# Render-farm ASN deny map — generated by scripts/gen-farm-nginx.mjs.',
  '# Sources: RIPEstat announced prefixes for ASNs: ' + FARM_ASNS.join(', '),
  '# Regenerate weekly (PM2 pmp-farm-asn-map). Residential ISPs must never',
  '# be added to FARM_ASNS — only pure cloud/hosting networks.',
  'geo $farm_asn {',
  '    default 0;',
  ...deduped.map((c) => `    ${c.cidr} 1; # AS${c.asn}`),
  '}',
  '',
].join('\n');

const snippet = '# 403 for requests from render-farm ASN prefixes (zz-farm-asn.conf geo map).\nif ($farm_asn) { return 403; }\n';

if (DRY) {
  console.log('--- geo (head) ---\n' + geo.split('\n').slice(0, 12).join('\n') + `\n... (${cidrs.length} entries)`);
  console.log('--- snippet ---\n' + snippet);
  process.exit(0);
}

fs.writeFileSync(GEO_FILE, geo);
fs.mkdirSync('/etc/nginx/snippets', { recursive: true });
fs.writeFileSync(SNIPPET, snippet);
console.log(`wrote ${GEO_FILE} + ${SNIPPET}`);

// Idempotent include insertion — every site that already includes the junk
// filter gets the farm filter right behind it.
for (const f of fs.readdirSync(SITES_DIR)) {
  const p = `${SITES_DIR}/${f}`;
  const s = fs.readFileSync(p, 'utf8');
  if (s.includes('farm_asn_filter.conf')) { console.log(`${f}: already included`); continue; }
  if (!s.includes(JUNK_INCLUDE)) { console.log(`${f}: no junk filter include — skipped`); continue; }
  const next = s.replace(JUNK_INCLUDE, `${JUNK_INCLUDE}\n${INCLUDE_LINE}`);
  fs.writeFileSync(p, next);
  console.log(`${f}: include inserted`);
}

const t = execSync('nginx -t 2>&1').toString();
console.log(t.trim());
if (!t.includes('successful')) { console.error('nginx -t FAILED — not reloading'); process.exit(1); }
execSync('systemctl reload nginx');
console.log('nginx reloaded');
